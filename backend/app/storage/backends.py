"""Object storage: the local filesystem and Oracle Object Storage.

What this is for
----------------
Three kinds of thing are stored: the CSV an operator uploaded, the offer
letters the recruiting module generates, and the onboarding documents the
HR module keeps. The production target is Oracle Object Storage
(``STORAGE_BACKEND=oci``), because the deployment's local disk is ephemeral
and a document that vanishes on every redeploy is a document that does not
exist (audit finding A5-02).

The verification contract
-------------------------
``save`` is not enough. A storage backend that reports success but loses the
bytes is worse than one that fails loudly, because the caller has already
moved on. Every write therefore carries a checksum:

* the SHA-256 of the payload is computed before the write;
* the checksum travels with the object (as object metadata on OCI, and as
  the value of a read-back comparison on the local filesystem);
* :meth:`StorageBackend.save_verified` reads the object back and compares
  the checksum, and raises if they differ.

A caller that needs to know the write really landed uses ``save_verified``.
A caller that only needs the bytes to be there uses ``save``.
"""
from __future__ import annotations

import hashlib
import os
import tempfile
from abc import ABC, abstractmethod

from app.core.config import settings
from app.core.observability import get_logger

log = get_logger("librepeople.storage")

#: The metadata key the checksum travels under.
CHECKSUM_METADATA_KEY = "sha256"

#: The URL prefix of the authenticated download route
#: (``GET /api/v1/files/{path}`` in :mod:`app.main`). Replaces the removed
#: unauthenticated ``/files/`` static mount; values generated by
#: :meth:`LocalStorage.url_for` point here.
AUTHORISED_FILES_PREFIX = "/api/v1/files/"


class StorageError(RuntimeError):
    """A storage operation failed."""


class ChecksumMismatch(StorageError):
    """What was written is not what was read back."""


def checksum(data: bytes) -> str:
    """The SHA-256 of a payload, as lowercase hex."""
    return hashlib.sha256(data).hexdigest()


class StorageBackend(ABC):
    """The interface every storage backend implements."""

    @abstractmethod
    def save(
        self, key: str, data: bytes, content_type: str = "application/octet-stream"
    ) -> str:
        """Persist bytes under ``key`` and return a retrievable URL or path."""

    @abstractmethod
    def read(self, key: str) -> bytes:
        """Return the bytes stored under ``key``.

        Raises :class:`StorageError` when the object is not there.
        """

    @abstractmethod
    def url_for(self, key: str) -> str:
        """Return a URL (or local path) to retrieve the object."""

    def delete(self, key: str) -> bool:
        """Delete an object. Returns True if it was deleted."""
        return False

    def exists(self, key: str) -> bool:
        """Check if an object exists."""
        return False

    def checksum(self, key: str) -> str | None:
        """The checksum of the stored object, or None if it cannot be read."""
        try:
            return checksum(self.read(key))
        except StorageError:
            return None

    def save_verified(
        self, key: str, data: bytes, content_type: str = "application/octet-stream"
    ) -> str:
        """Save, read back, and prove the bytes arrived intact.

        This is the write an import uses. If the read-back does not match,
        the write is treated as a failure and the caller rolls back.
        """
        expected = checksum(data)
        url = self.save(key, data, content_type)
        actual = self.checksum(key)
        if actual != expected:
            raise ChecksumMismatch(
                f"The object written to {key} did not read back intact."
            )
        return url


class LocalStorage(StorageBackend):
    """The filesystem, used in development and in the test suites."""

    def __init__(self, base_dir: str):
        self.base_dir = base_dir
        os.makedirs(self.base_dir, exist_ok=True)

    def _path(self, key: str) -> str:
        # The key is built by the application, but a key that escapes the
        # base directory would let a caller write anywhere on the disk.
        path = os.path.abspath(os.path.join(self.base_dir, key))
        root = os.path.abspath(self.base_dir)
        if not path.startswith(root + os.sep) and path != root:
            raise StorageError("The storage key is outside the storage root.")
        return path

    def save(
        self, key: str, data: bytes, content_type: str = "application/octet-stream"
    ) -> str:
        path = self._path(key)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        # Write to a temporary file and rename, so a reader never sees a
        # half-written object.
        handle, temporary = tempfile.mkstemp(dir=os.path.dirname(path))
        try:
            with os.fdopen(handle, "wb") as fh:
                fh.write(data)
            os.replace(temporary, path)
        except Exception:
            if os.path.exists(temporary):
                os.unlink(temporary)
            raise
        return self.url_for(key)

    def read(self, key: str) -> bytes:
        path = self._path(key)
        if not os.path.exists(path):
            raise StorageError(f"No object stored under {key}.")
        with open(path, "rb") as fh:
            return fh.read()

    def url_for(self, key: str) -> str:
        # The static ``/files`` mount was removed (item 9); documents are
        # served through the authenticated route instead.
        return f"{AUTHORISED_FILES_PREFIX}{key}"

    def delete(self, key: str) -> bool:
        path = self._path(key)
        if os.path.exists(path):
            os.unlink(path)
            return True
        return False

    def exists(self, key: str) -> bool:
        return os.path.exists(self._path(key))


class OCIObjectStorage(StorageBackend):
    """Oracle Object Storage, through the OCI Python SDK."""

    def __init__(self, namespace: str, bucket: str, config_file: str, profile: str):
        import oci  # lazy import: the SDK is not needed for local development

        self._oci = oci
        config = oci.config.from_file(
            os.path.expanduser(config_file), profile
        )
        self.client = oci.object_storage.ObjectStorageClient(config)
        self.namespace = namespace
        self.bucket = bucket
        self.region = config.get("region", "ap-hyderabad-1")

    def save(
        self, key: str, data: bytes, content_type: str = "application/octet-stream"
    ) -> str:
        digest = checksum(data)
        self.client.put_object(
            self.namespace,
            self.bucket,
            key,
            data,
            content_type=content_type,
            metadata={CHECKSUM_METADATA_KEY: digest},
        )
        return self.url_for(key)

    def read(self, key: str) -> bytes:
        try:
            response = self.client.get_object(self.namespace, self.bucket, key)
            return response.data.content
        except Exception as exc:  # noqa: BLE001
            raise StorageError(f"Could not read the object stored under {key}.") from exc

    def url_for(self, key: str) -> str:
        # A pre-authenticated request for read access. Seven days is the
        # maximum the service allows for a PAR.
        try:
            from datetime import datetime, timedelta, timezone

            expiry = datetime.now(timezone.utc) + timedelta(days=7)
            details = self._oci.object_storage.models.CreatePreauthenticatedRequestDetails(
                name=f"par-{key.replace('/', '_')[:40]}",
                object_name=key,
                access_type="ObjectRead",
                time_expires=expiry,
            )
            par = self.client.create_preauthenticated_request(
                self.namespace, self.bucket, details
            ).data
            return f"https://objectstorage.{self.region}.oraclecloud.com{par.access_uri}"
        except Exception:  # noqa: BLE001
            return f"oci://{self.namespace}/{self.bucket}/{key}"

    def delete(self, key: str) -> bool:
        try:
            self.client.delete_object(self.namespace, self.bucket, key)
            return True
        except Exception:  # noqa: BLE001
            return False

    def exists(self, key: str) -> bool:
        try:
            self.client.head_object(self.namespace, self.bucket, key)
            return True
        except Exception:  # noqa: BLE001
            return False

    def checksum(self, key: str) -> str | None:
        try:
            response = self.client.head_object(self.namespace, self.bucket, key)
            metadata = response.headers or {}
            return metadata.get(CHECKSUM_METADATA_KEY)
        except Exception:  # noqa: BLE001
            return None

    def list_objects(self, prefix: str = "") -> list[str]:
        try:
            response = self.client.list_objects(
                self.namespace, self.bucket, prefix=prefix
            )
            return [obj.name for obj in (response.data.objects or [])]
        except Exception:  # noqa: BLE001
            return []


def get_storage() -> StorageBackend:
    """The storage backend this deployment is configured to use."""
    if (
        settings.STORAGE_BACKEND == "oci"
        and settings.OCI_NAMESPACE
        and settings.OCI_BUCKET_NAME
    ):
        try:
            return OCIObjectStorage(
                namespace=settings.OCI_NAMESPACE,
                bucket=settings.OCI_BUCKET_NAME,
                config_file=settings.OCI_CONFIG_FILE,
                profile=settings.OCI_PROFILE,
            )
        except Exception as exc:  # noqa: BLE001
            log.error(
                "the OCI storage backend is unavailable; falling back to local",
                exc_type=type(exc).__name__,
            )
    return LocalStorage(settings.LOCAL_STORAGE_DIR)
