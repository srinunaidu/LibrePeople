"""Persisted statutory filing records (filing-persistence).

One row per saved generation of a filing from stored payslip JSON — no
recompute, no challan payment, no upload to any authority. The generated
bytes themselves are never stored here: ``content_ref`` is a reference
only (the download filename convention), plus the SHA-256 ``content_hash``
that proves what was generated. Attachments follow the same rule —
references only, no binary storage.

Lifecycle (``status``): ``Draft`` → ``Submitted`` → ``Accepted`` /
``Rejected`` → ``Resubmitted``. A resubmission never mutates the original
row: it marks the rejected row ``Resubmitted`` (terminal) and opens a new
``Draft`` row with ``version = N + 1`` linked through ``supersedes_id``.
``Accepted`` is likewise terminal. Every transition writes a chained audit
row via :func:`app.core.audit.record_audit`.
"""
from __future__ import annotations

from datetime import date, datetime, timezone

from sqlalchemy import CheckConstraint, Date, DateTime, ForeignKey, Index, Integer, String
from sqlalchemy.orm import Mapped, mapped_column

from app.models.base import Base

#: Canonical filing types. Aliases (``24q`` → ``24q_quarterly``,
#: ``form16`` → ``form16_annual``, ``pt_return`` → ``pt_challan``) are
#: normalised to these at the API boundary; only canonical values persist.
FILING_TYPES = ("24q_quarterly", "form16_annual", "pf_ecr", "esi_return", "pt_challan")

#: The full lifecycle. ``Resubmitted`` and ``Accepted`` are terminal.
FILING_STATUSES = ("Draft", "Submitted", "Accepted", "Rejected", "Resubmitted")

#: Legal transitions: action → (from-status, to-status).
FILING_TRANSITIONS = {
    "submit": ("Draft", "Submitted"),
    "accept": ("Submitted", "Accepted"),
    "reject": ("Submitted", "Rejected"),
}

FILING_STATUS_CHECK = (
    "status IN ('Draft','Submitted','Accepted','Rejected','Resubmitted')"
)


class FilingRecord(Base):
    """A saved generation of a statutory filing, versioned across resubmissions."""

    __tablename__ = "filing_records"
    __table_args__ = (
        Index("ix_filing_records_type_period", "filing_type", "period"),
        Index("ix_filing_records_status", "status"),
        CheckConstraint(FILING_STATUS_CHECK, name="ck_filing_record_status"),
    )

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    filing_type: Mapped[str] = mapped_column(String(40), nullable=False)
    #: ``YYYY-MM`` for monthly filings, ``YYYY`` for the annual Form 16.
    period: Mapped[str] = mapped_column(String(7), nullable=False)
    #: PT state (KA/MH/TN/TG/WB) for ``pt_challan``; NULL otherwise.
    state: Mapped[str | None] = mapped_column(String(2), nullable=True)
    status: Mapped[str] = mapped_column(String(20), nullable=False, default="Draft")
    #: SHA-256 of the exact generated bytes.
    content_hash: Mapped[str] = mapped_column(String(64), nullable=False)
    #: Reference only (download filename); never the bytes themselves.
    content_ref: Mapped[str | None] = mapped_column(String(255), nullable=True)
    version: Mapped[int] = mapped_column(Integer, nullable=False, default=1)
    #: The prior version this row resubmits; NULL for first versions.
    supersedes_id: Mapped[int | None] = mapped_column(
        ForeignKey("filing_records.id"), nullable=True
    )
    submitted_by: Mapped[int | None] = mapped_column(Integer, nullable=True)
    submitted_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)
    #: Keep-all until an owner-defined retention policy lands; NULL = retain.
    retention_until: Mapped[date | None] = mapped_column(Date, nullable=True)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, default=lambda: datetime.now(timezone.utc)
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        default=lambda: datetime.now(timezone.utc),
        onupdate=lambda: datetime.now(timezone.utc),
    )
